const formatUptime = (s) => {
  const d = Math.floor(s / 86400)
  const h = Math.floor((s % 86400) / 3600)
  const m = Math.floor((s % 3600) / 60)
  return `${d}d ${h}h ${m}m`
}

const section = (title, cmds, prefix) => {
  const lines = cmds.map(c => `| ⌬ ${prefix}${c}`)
  return [`\n.————< ${title} >————.`, ...lines, `'————————————————'`].join('\n')
}

